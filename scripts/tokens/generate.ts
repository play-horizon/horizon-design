/**
 * Builds the library's token outputs from `tokens.ts`, before the docs site, the tests and the
 * package are built (`pnpm tokens`, run by the `prepare`, `dev`, `check`, `test` and `build`
 * scripts):
 *
 * - `src/lib/generated/theme.css`: each theme's CSS variables (OKLCH) and the Tailwind theme that
 *   maps them to utilities (`--color-surface: var(--surface)`, `--shadow-md: var(--elevation-md)`);
 * - `src/lib/generated/tokens.ts`: every colour token of each theme in both forms, its OKLCH text
 *   and its sRGB hex, exported as `horizon-design/tokens` for the colours needed before any CSS
 *   loads.
 *
 * Both files are gitignored: the build is what converts the OKLCH values to hex, with colorjs.io
 * (CSS Color 4's conversion, so the hex is the colour a browser paints for the same OKLCH value).
 * @module
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import Color from 'colorjs.io';
import {
	colorTokenDocs,
	colors,
	elevation,
	themes,
	toOklchText,
	type ColorToken,
	type Theme
} from './tokens.ts';

const root = resolve(import.meta.dirname, '../..');
const outDir = resolve(root, 'src/lib/generated');
const banner =
	'Generated by scripts/tokens/generate.ts from scripts/tokens/tokens.ts: do not edit.';
const tokenNames = Object.keys(colorTokenDocs) as ColorToken[];
const shadowNames = ['sm', 'md', 'lg'] as const;
const elevationNames = [...shadowNames, 'highlight'] as const;

const selectors: Record<Theme, string> = {
	dark: ":root,\n[data-theme='dark']",
	light: "[data-theme='light']"
};

function themeBlock(theme: Theme): string {
	const lines = [`${selectors[theme]} {`, `\tcolor-scheme: ${theme};`];
	for (const name of tokenNames) {
		lines.push(
			`\t/* ${colorTokenDocs[name]} */`,
			`\t--${name}: ${toOklchText(colors[theme][name])};`
		);
	}
	for (const name of elevationNames)
		lines.push(`\t--elevation-${name}: ${elevation[theme][name]};`);
	lines.push('}');
	return lines.join('\n');
}

function tailwindTheme(): string {
	const lines = ['@theme inline {'];
	for (const name of tokenNames) lines.push(`\t--color-${name}: var(--${name});`);
	for (const name of shadowNames) lines.push(`\t--shadow-${name}: var(--elevation-${name});`);
	lines.push('\t--inset-shadow-highlight: var(--elevation-highlight);');
	lines.push('}');
	return lines.join('\n');
}

/** The theme CSS: both themes' variables, then the Tailwind theme. */
export function themeCss(): string {
	return `/* ${banner} */\n\n${themes.map(themeBlock).join('\n\n')}\n\n${tailwindTheme()}\n`;
}

/**
 * Converts an `oklch()` colour to lowercase sRGB hex: `#rrggbb` when opaque, `#rrggbbaa`
 * otherwise. There is no gamut mapping: a colour outside sRGB is refused, so every token is a
 * colour its CSS and its hex show the same way.
 *
 * @example
 * oklchToHex('oklch(1 0 0 / 0.5)'); // '#ffffff80'
 * @throws Error when the text isn't an `oklch()` colour, or the colour lies outside sRGB.
 */
export function oklchToHex(text: string): string {
	const color = new Color(text);
	if (color.spaceId !== 'oklch') throw new Error(`"${text}" is not an oklch() colour`);
	if (!color.inGamut('srgb')) throw new Error(`${text} is outside sRGB`);
	return color.to('srgb').toString({ format: 'hex', collapse: false });
}

/** A colour token's value in both forms. */
interface TokenValue {
	oklch: string;
	hex: string;
}

/** Every colour token of each theme, as its OKLCH text and its sRGB hex, keyed by theme then token. */
export function tokenValues(): Record<Theme, Record<ColorToken, TokenValue>> {
	const entries = themes.map((theme) => {
		const values = tokenNames.map((name) => {
			const oklch = toOklchText(colors[theme][name]);
			try {
				return [name, { oklch, hex: oklchToHex(oklch) }] as const;
			} catch (error) {
				throw new Error(`${theme} token "${name}": ${(error as Error).message}`, { cause: error });
			}
		});
		return [theme, Object.fromEntries(values)] as const;
	});
	return Object.fromEntries(entries) as Record<Theme, Record<ColorToken, TokenValue>>;
}

/** The exported module: the token values of each theme in both forms, with their types. */
export function tokensModule(): string {
	const values = tokenValues();
	const body = themes
		.map((theme) => {
			const rows = tokenNames.map((name) => {
				const { oklch, hex } = values[theme][name];
				return `\t\t'${name}': { oklch: '${oklch}', hex: '${hex}' }`;
			});
			return `\t${theme}: {\n${rows.join(',\n')}\n\t}`;
		})
		.join(',\n');
	return `/**
 * ${banner}
 *
 * The colour tokens of each theme in both forms: \`oklch\`, the value the theme CSS uses, and
 * \`hex\`, the same colour in sRGB (\`#rrggbb\`, or \`#rrggbbaa\` for translucent tokens),
 * converted when the library is built. Every token lies inside sRGB, so both forms are the same
 * colour. For colours needed before any CSS loads, such as Electron's \`backgroundColor\`
 * (\`tokenValues.dark.background.hex\`) and the website's \`<meta name="theme-color">\`.
 * @module
 */

/** A theme's name. */
export type Theme = ${themes.map((t) => `'${t}'`).join(' | ')};

/** A semantic colour token's name. */
export type ColorToken =
${tokenNames.map((n) => `\t| '${n}'`).join('\n')};

/** A colour token's value in both forms. */
export interface TokenValue {
\t/** The OKLCH value the theme CSS uses, such as \`oklch(0.202 0.029 268.7)\` or \`oklch(1 0 0 / 0.5)\`. */
\treadonly oklch: string;
\t/** The same colour as lowercase sRGB hex: \`#rrggbb\`, or \`#rrggbbaa\` when translucent. */
\treadonly hex: string;
}

/** Each theme's colour tokens, in both forms. */
export const tokenValues: Readonly<Record<Theme, Readonly<Record<ColorToken, TokenValue>>>> = {
${body}
};
`;
}

function write(path: string, text: string): void {
	mkdirSync(dirname(path), { recursive: true });
	writeFileSync(path, text);
}

if (import.meta.main) {
	write(resolve(outDir, 'theme.css'), themeCss());
	write(resolve(outDir, 'tokens.ts'), tokensModule());
}
